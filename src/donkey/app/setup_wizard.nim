# ── Pure helpers (unit-tested) ────────────────────────────────────────────────

func providerEnvVar*(providerName: string): string =
  ## Returns the environment variable name that holds the API key for a
  ## provider: the first env name of its descriptor. Empty for unknown ids.
  let descriptor = providerDescriptor(providerName)
  if descriptor.isNone or descriptor.get().envNames.len == 0:
    return ""
  descriptor.get().envNames[0]

func providerCredentialFromEnv*(providerName: string):
    tuple[envName: string, value: string] =
  ## The credential the environment holds for a provider, together with the
  ## env name it came from. A plural `*_KEYS` pool is returned whole (joined by
  ## commas) under its plural name, so setup keeps every key instead of
  ## collapsing the pool to its first entry. `envName` is empty when the
  ## provider has no environment credential; endpoint-configured providers
  ## (`atNone`, e.g. ollama) never yield an API key.
  let descriptor = providerDescriptor(providerName)
  if descriptor.isNone:
    return ("", "")
  let d = descriptor.get()
  if d.authType == atNone:
    return ("", "")
  for envName in d.envNames:
    let single = getEnv(envName).strip()
    if single.len > 0:
      return (envName, single)
    let pluralName = poolEnvName(envName)
    let plural = splitKeys(getEnv(pluralName))
    if plural.len > 0:
      return (pluralName, plural.join(","))
  ("", "")

func providerKeyFromEnv*(providerName: string): string =
  ## The first configured credential for a provider, considering every
  ## descriptor env name and the plural `*_KEYS` form. Endpoint-configured
  ## providers (`atNone`, e.g. ollama) never yield an API key.
  let credential = providerCredentialFromEnv(providerName)
  let keys = splitKeys(credential.value)
  if keys.len > 0: keys[0] else: ""

func buildTomlContent*(home: string;
                       logLevel = "info";
                       runtime = "docker";
                       defaultProvider = "";
                       defaultModel = ""): string =
  ## Generates minimal donkey.toml content.
  result = "# " & AppName & " configuration\n" &
  "# Generated by `" & AppSlug & " setup`\n\n" &
  "[" & ConfigSectionName & "]\n" &
  "home      = \"" & home & "\"\n" &
  "paddocks  = \"" & home / "paddocks" & "\"\n" &
  "log_file  = \"" & home / LogFileName & "\"\n" &
  "log_level = \"" & logLevel & "\"\n" &
  "wiring    = true\n"
  if defaultProvider.len > 0:
    result &= "default_provider = \"" & defaultProvider & "\"\n"
  if defaultModel.len > 0:
    result &= "default_model = \"" & defaultModel & "\"\n"
  result &= "\n" &
  "[sandbox]\n" &
  "mode    = \"oci\"\n" &
  "runtime = \"" & runtime & "\"\n" &
  "image = \"alpine\"\n" &
  "allow_host_fallback = false\n" &
  "allow_network = false\n" &
  "read_only_rootfs = true\n"

func channelToken(channels: seq[(string, string)]; name: string): string =
  for (ch, tok) in channels:
    if ch == name: return tok
  ""

type
  ProviderSecret* = tuple[provider: string, envName: string, key: string]
    ## A selected provider, the env name its key came from (empty when the
    ## operator typed a new key), and the key/pool value itself.

func buildEnvContent*(providers: seq[ProviderSecret];
                      channels: seq[(string, string)];
                      braveApiKey = ""): string =
  ## Generates donkey.env content from wizard answers.
  ## providers: seq of (provider_name, source_env_name, api_key)
  ## channels: seq of (channel_name, token)
  ##
  ## The key is written under the env name it came from, so a plural `*_KEYS`
  ## pool stays plural and provider-specific names (OPENCODE_GO_API_KEY,
  ## ZEN_API_KEY) stay specific. Providers that share an env name
  ## (opencode-go/zen with OPENCODE_API_KEY) are written once: dotenv keeps the
  ## first value.
  result = "# " & AppName & " secrets — keep this file private (chmod 600)\n"
  result &= "# Generated by `" & AppSlug & " setup`\n\n"
  result &= "# Recommended local default for Multigraph Memory:\n"
  result &= "# DONKEY_MAGMA_SQLITE_PATH=/absolute/path/to/donkey-magma.sqlite\n"
  result &= "# DONKEY_SQLITE_VEC_PATH=/absolute/path/to/vec0\n"
  result &= "# PostgreSQL remains optional for larger installs:\n"
  result &= "#   docker compose up -d postgres\n"
  result &= "#   if 5432 is busy: DONKEY_PG_PORT=5433 docker compose up -d postgres\n"
  result &= "# DONKEY_PG_DSN=host=127.0.0.1 user=postgres password=donkey_pass dbname=donkey port=5432\n\n"
  result &= "# Providers\n"
  var writtenEnv: seq[string]
  for (provName, sourceEnv, provKey) in providers:
    if provKey.len == 0:
      continue
    # Local providers have no key; writing one would clobber a real endpoint
    # set in the operator's shell.
    let descriptor = providerDescriptor(provName)
    if descriptor.isSome and descriptor.get().authType == atNone:
      continue
    let envVar =
      if sourceEnv.len > 0: sourceEnv
      else: providerEnvVar(provName)
    if envVar.len > 0 and envVar notin writtenEnv:
      writtenEnv.add envVar
      result &= envVar & "=" & provKey & "\n"
  result &= "\n# Optional web search\n"
  result &= "# Used by the `web_search` tool (Brave Search API)\n"
  result &= "BRAVE_API_KEY=" & braveApiKey & "\n"
  result &= "\n# Channels\n"
  result &= "TELEGRAM_BOT_TOKEN="   & channelToken(channels, "telegram") & "\n"
  result &= "DISCORD_BOT_TOKEN="    & channelToken(channels, "discord")  & "\n"
  result &= "WECOM_CORP_ID="        & channelToken(channels, "wecom_corp_id")     & "\n"
  result &= "WECOM_CORP_SECRET="    & channelToken(channels, "wecom_corp_secret") & "\n"
  result &= "WECOM_AGENT_ID="       & channelToken(channels, "wecom_agent_id")    & "\n"
  result &= "WECOM_CALLBACK_TOKEN=" & channelToken(channels, "wecom_callback")    & "\n"

func buildEnvContent*(providers: seq[(string, string)];
                      channels: seq[(string, string)];
                      braveApiKey = ""): string =
  ## Backwards-compatible form: (provider_name, api_key) without a source env
  ## name. The key is written under the provider's first descriptor env name.
  var secrets: seq[ProviderSecret]
  for (provName, provKey) in providers:
    secrets.add((provider: provName, envName: providerEnvVar(provName),
                 key: provKey))
  buildEnvContent(secrets, channels, braveApiKey)

