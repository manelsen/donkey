## Setup wizard — interactive first-run configuration for the Donkey operator.
##
## Pure helpers (buildTomlContent, buildEnvContent, providerEnvVar,
## setupAlreadyDone) are unit-tested.  The interactive wizard (runSetupWizard)
## drives stdin/stdout and is tested manually.
##
## Output files:
##   ~/.config/donkey/donkey.toml  — main config (home, paddocks, log level, …)
##   ~/.config/donkey/donkey.env   — secrets (API keys, bot tokens); chmod 600

import std/[os, strutils, terminal]
import ../core/app_meta
import ../core/providers/smart_routing

# ── Pure helpers (unit-tested) ────────────────────────────────────────────────

func providerEnvVar*(providerName: string): string =
  ## Returns the environment variable name that holds the API key for a provider.
  case providerName
  of "zai-coding": "ZAI_CODING_API_KEY"
  of "zai":        "ZAI_API_KEY"
  of "zai-anthropic": "ZAI_ANTHROPIC_API_KEY"
  of "openrouter": "OPENROUTER_API_KEY"
  of "anthropic":  "ANTHROPIC_API_KEY"
  of "gemini":     "GEMINI_API_KEY"
  of "minimax":    "MINIMAX_API_KEY"
  of "deepseek":   "DEEPSEEK_API_KEY"
  of "openai":     "OPENAI_API_KEY"
  else:            ""

func buildTomlContent*(home: string;
                       logLevel = "info";
                       runtime = "docker";
                       defaultProvider = "";
                       defaultModel = ""): string =
  ## Generates minimal donkey.toml content.
  result = "# " & AppName & " configuration\n" &
  "# Generated by `" & AppSlug & " setup`\n\n" &
  "[" & ConfigSectionName & "]\n" &
  "home      = \"" & home & "\"\n" &
  "paddocks  = \"" & home / "paddocks" & "\"\n" &
  "log_file  = \"" & home / LogFileName & "\"\n" &
  "log_level = \"" & logLevel & "\"\n" &
  "wiring    = true\n"
  if defaultProvider.len > 0:
    result &= "default_provider = \"" & defaultProvider & "\"\n"
  if defaultModel.len > 0:
    result &= "default_model = \"" & defaultModel & "\"\n"
  result &= "\n" &
  "[sandbox]\n" &
  "mode    = \"oci\"\n" &
  "runtime = \"" & runtime & "\"\n" &
  "image = \"alpine\"\n" &
  "allow_host_fallback = false\n" &
  "allow_network = false\n" &
  "read_only_rootfs = true\n"

func channelToken(channels: seq[(string, string)]; name: string): string =
  for (ch, tok) in channels:
    if ch == name: return tok
  ""

func buildEnvContent*(providers: seq[(string, string)];
                      channels: seq[(string, string)];
                      braveApiKey = ""): string =
  ## Generates donkey.env content from wizard answers.
  ## providers: seq of (provider_name, api_key)
  ## channels: seq of (channel_name, token)
  result = "# " & AppName & " secrets — keep this file private (chmod 600)\n"
  result &= "# Generated by `" & AppSlug & " setup`\n\n"
  result &= "# Recommended local default for Multigraph Memory:\n"
  result &= "# DONKEY_MAGMA_SQLITE_PATH=/absolute/path/to/donkey-magma.sqlite\n"
  result &= "# DONKEY_SQLITE_VEC_PATH=/absolute/path/to/vec0\n"
  result &= "# PostgreSQL remains optional for larger installs:\n"
  result &= "#   docker compose up -d postgres\n"
  result &= "#   if 5432 is busy: DONKEY_PG_PORT=5433 docker compose up -d postgres\n"
  result &= "# DONKEY_PG_DSN=host=127.0.0.1 user=postgres password=donkey_pass dbname=donkey port=5432\n\n"
  result &= "# Providers\n"
  for (provName, provKey) in providers:
    let envVar = providerEnvVar(provName)
    if envVar.len > 0:
      result &= envVar & "=" & provKey & "\n"
  result &= "\n# Optional web search\n"
  result &= "# Used by the `web_search` tool (Brave Search API)\n"
  result &= "BRAVE_API_KEY=" & braveApiKey & "\n"
  result &= "\n# Channels\n"
  result &= "TELEGRAM_BOT_TOKEN="   & channelToken(channels, "telegram") & "\n"
  result &= "DISCORD_BOT_TOKEN="    & channelToken(channels, "discord")  & "\n"
  result &= "WECOM_CORP_ID="        & channelToken(channels, "wecom_corp_id")     & "\n"
  result &= "WECOM_CORP_SECRET="    & channelToken(channels, "wecom_corp_secret") & "\n"
  result &= "WECOM_AGENT_ID="       & channelToken(channels, "wecom_agent_id")    & "\n"
  result &= "WECOM_CALLBACK_TOKEN=" & channelToken(channels, "wecom_callback")    & "\n"

proc configDirPath*(): string =
  getConfigDir() / ConfigDirName

proc configFilePath*(): string =
  configDirPath() / ConfigFileName

proc envFilePath*(): string =
  configDirPath() / EnvFileName

proc preferredSandboxRuntime*(): string =
  if findExe("docker").len > 0: return "docker"
  if findExe("podman").len > 0: return "podman"
  "docker"

proc providerDefaultChoice*(providers: seq[(string, string)]): string =
  if providers.len > 0: providers[0][0] else: ""

proc setupAlreadyDone*(): bool =
  ## Returns true if donkey.toml already exists in the user config directory.
  fileExists(configFilePath())

# ── Interactive wizard ────────────────────────────────────────────────────────

const Providers = [
  ("1", "zai-coding", "ZAI Coding    (GLM)           [recomendado]"),
  ("2", "zai-anthropic", "Z.AI Anthropic compat        [Claude-compatible]"),
  ("3", "openrouter", "OpenRouter    (300+ modelos)"),
  ("4", "anthropic",  "Anthropic     (Claude)"),
  ("5", "gemini",     "Google Gemini"),
  ("6", "openai",     "OpenAI        (GPT)"),
  ("7", "deepseek",   "DeepSeek"),
  ("8", "minimax",    "MiniMax"),
  ("9", "ollama",     "Ollama        (local, sem API key)"),
]

proc ask(prompt: string; default = ""): string =
  if default.len > 0:
    stdout.write(prompt & " [" & default & "]: ")
  else:
    stdout.write(prompt & ": ")
  stdout.flushFile()
  result = stdin.readLine().strip()
  if result.len == 0:
    result = default

proc askSecret(prompt: string): string =
  stdout.write(prompt & ": ")
  stdout.flushFile()
  when defined(windows):
    result = stdin.readLine().strip()
  else:
    result = readPasswordFromStdin("").strip()

proc printHeader =
  echo ""
  echo "╔══════════════════════════════════════════════════╗"
  echo "║        🐴  " & AppName & "  " & AppSlug & " setup           ║"
  echo "╚══════════════════════════════════════════════════╝"
  echo ""

proc runSetupWizard*(home: string) =
  ## Interactive first-run wizard.  Writes donkey.toml and donkey.env.
  printHeader()

  let cfgDir = configDirPath()
  let cfgPath = configFilePath()
  let envPath = envFilePath()

  if setupAlreadyDone():
    echo "Configuração já existe em " & cfgPath
    stdout.write("Reconfigurar? [s/N]: ")
    stdout.flushFile()
    let ans = stdin.readLine().strip().toLowerAscii()
    if ans != "s" and ans != "sim" and ans != "y" and ans != "yes":
      echo "Nada alterado."
      return

  # ── [1/3] Providers ──────────────────────────────────────────────────────────
  echo "[1/3] Providers de IA"
  echo ""
  var providers: seq[(string, string)] = @[]

  block providerLoop:
    while true:
      echo "  Providers disponíveis:"
      for (num, _, label) in Providers:
        echo "    " & num & ") " & label
      echo ""
      let provChoice = ask("  Escolha (1-" & $Providers.len & ")", "1")
      var providerName = ""
      for (num, name, _) in Providers:
        if num == provChoice:
          providerName = name
          break
      if providerName.len == 0:
        providerName = "zai-coding"

      if providerName != "ollama":
        let envVar = providerEnvVar(providerName)
        let existing = getEnv(envVar)
        var apiKey = ""
        if existing.len > 0:
          echo "    (usando " & envVar & " do ambiente)"
          apiKey = existing
        else:
          apiKey = askSecret("    API key (" & envVar & ")")
        if apiKey.len > 0:
          providers.add((providerName, apiKey))
          echo "    ✓ " & providerName & " adicionado"
      else:
        providers.add((providerName, ""))
        echo "    ✓ " & providerName & " adicionado (local, sem key)"

      echo ""
      stdout.write("  Adicionar outro provider? [s/N]: ")
      stdout.flushFile()
      let more = stdin.readLine().strip().toLowerAscii()
      if more != "s" and more != "sim" and more != "y" and more != "yes":
        break providerLoop
      echo ""

  echo ""

  # ── [1.5/3] Heartbeat / provider default ───────────────────────────────────
  var defaultProvider = providerDefaultChoice(providers)
  var defaultModel = ""
  echo "Heartbeat é o turno proativo periódico do Donkey."
  echo "Quando um usuário ainda não escolheu preferências próprias,"
  echo "o provider/model default da instalação será usado nesse primeiro momento."
  echo ""
  if providers.len > 0:
    echo "  Providers configurados:"
    for i, item in providers:
      echo "    " & $(i + 1) & ") " & item[0]
    let rawChoice = ask("  Provider padrão do heartbeat e de novos usuários (1-" &
                        $providers.len & ")", "1")
    try:
      let idx = max(1, parseInt(rawChoice)) - 1
      if idx >= 0 and idx < providers.len:
        defaultProvider = providers[idx][0]
    except ValueError:
      discard
    let suggestedModel =
      if defaultProvider.len > 0: defaultModelForProvider(defaultProvider) else: ""
    defaultModel = ask("  Modelo padrão para " & defaultProvider, suggestedModel)
  else:
    echo "  Nenhum provider foi configurado ainda; pulando o default do heartbeat."
  echo ""

  # ── [1.6/3] Web search ─────────────────────────────────────────────────────
  echo "Busca web opcional"
  echo "  O tool `web_search` usa a Brave Search API."
  echo "  Se você preencher `BRAVE_API_KEY`, o agente poderá pesquisar na web."
  let existingBrave = getEnv("BRAVE_API_KEY")
  let braveApiKey =
    if existingBrave.len > 0:
      echo "    (usando BRAVE_API_KEY do ambiente)"
      existingBrave
    else:
      askSecret("  Brave Search API key  (enter para pular)")
  echo ""

  # ── [2/3] Canais ────────────────────────────────────────────────────────────
  echo "[2/3] Canais de mensagem  (enter para pular)"
  echo ""
  var channels: seq[(string, string)]

  let existingTg = getEnv("TELEGRAM_BOT_TOKEN")
  let tgToken =
    if existingTg.len > 0:
      echo "    (usando TELEGRAM_BOT_TOKEN do ambiente)"
      existingTg
    else:
      ask("  Telegram bot token  (BotFather → /newbot)")
  if tgToken.len > 0: channels.add(("telegram", tgToken))

  let existingDc = getEnv("DISCORD_BOT_TOKEN")
  let dcToken =
    if existingDc.len > 0:
      echo "    (usando DISCORD_BOT_TOKEN do ambiente)"
      existingDc
    else:
      ask("  Discord bot token   (developers.discord.com)")
  if dcToken.len > 0: channels.add(("discord", dcToken))

  let wcCorpId = ask("  WeCom Corp ID       (deixe em branco para pular)")
  if wcCorpId.len > 0:
    channels.add(("wecom_corp_id", wcCorpId))
    let wcSecret   = askSecret("  WeCom Corp Secret")
    let wcAgentId  = ask("  WeCom Agent ID")
    let wcCallback = askSecret("  WeCom Callback Token")
    channels.add(("wecom_corp_secret", wcSecret))
    channels.add(("wecom_agent_id",    wcAgentId))
    channels.add(("wecom_callback",    wcCallback))

  echo ""

  # ── [3/3] Diretório ─────────────────────────────────────────────────────────
  echo "[3/3] Diretório"
  echo ""
  let chosenHome = ask("  Diretório home do Donkey", home)
  let runtime = preferredSandboxRuntime()
  echo "  Runtime OCI detectado: " & runtime

  # ── Gravando ─────────────────────────────────────────────────────────────────
  echo ""
  echo "Gravando..."

  try:
    createDir(chosenHome)
    createDir(chosenHome / "paddocks")
    createDir(chosenHome / "state")
  except CatchableError as e:
    echo "Erro ao criar " & chosenHome & ": " & e.msg
    return

  try:
    createDir(cfgDir)
  except CatchableError as e:
    echo "Erro ao criar " & cfgDir & ": " & e.msg
    return

  let tomlPath = cfgPath
  let tomlContent = buildTomlContent(
    chosenHome,
    runtime = runtime,
    defaultProvider = defaultProvider,
    defaultModel = defaultModel,
  )
  try:
    writeFile(tomlPath, tomlContent)
    echo "  ✓ " & tomlPath
  except CatchableError as e:
    echo "  ✗ " & tomlPath & ": " & e.msg
    return

  let envContent = buildEnvContent(providers, channels, braveApiKey)
  try:
    writeFile(envPath, envContent)
    when not defined(windows):
      discard execShellCmd("chmod 600 \"" & envPath & "\"")
    echo "  ✓ " & envPath & "  (chmod 600)"
  except CatchableError as e:
    echo "  ✗ " & envPath & ": " & e.msg
    return

  echo ""
  echo "Pronto! Próximos passos:"
  echo ""
  echo "  " & AppSlug & " doctor --config " & tomlPath
  echo "  " & AppSlug & " start --config " & tomlPath
  echo ""
  echo "Opcional:"
  echo "  " & AppSlug & " service install --config " & tomlPath
  echo "  " & AppSlug & " service start"
  echo ""
  echo "Para editar as configurações depois:"
  echo "  " & tomlPath
  echo "  " & envPath
  echo ""
